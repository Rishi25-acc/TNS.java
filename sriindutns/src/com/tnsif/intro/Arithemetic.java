package com.tnsif.intro;

public class Arithemetic {
	public static void main(String [] args)
	{
		int a=10;
		int b=20;
		int r;
		r=a+b;
		System.out.println(r);
		r=a-b;
		System.out.println(r);
		r=a*b;
		System.out.println(r);
		r=a/b;
		System.out.println(r);
		r=a%b;
		System.out.println(r);
	}
	
}
